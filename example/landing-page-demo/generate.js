/**
 * Landing Page Demo — Generate a complete Vite + React + TypeScript project
 *
 * Generates a production-ready landing page project with deploy-to-Vercel
 * support, using SCG's core features: ParamHelper, StringHelper, Scaffold,
 * Pipeline, FileHelper, CommandHelper, and Watcher.
 *
 * Usage:
 *   node example/landing-page-demo/generate.js --name=MyStartup --title="My Startup" --description="The best product ever"
 *   node example/landing-page-demo/generate.js --name=Acme --watch
 *
 * Then run the generated project:
 *   cd generated/myapp-landing && pnpm install && pnpm dev
 *
 * Deploy to Vercel:
 *   cd generated/myapp-landing && pnpm deploy
 *
 * Features demonstrated:
 *   1. ParamHelper    — CLI argument parsing (--name, --title, --description)
 *   2. StringHelper   — String transformations for project naming
 *   3. Scaffold       — Bulk file generation (React components, CSS, HTML)
 *   4. Pipeline       — README generation with Handlebars + transforms
 *   5. FileHelper     — Config file generation (package.json, tsconfig, vite.config, vercel.json)
 *   6. CommandHelper   — Shell command execution (file listing, chmod)
 *   7. Watcher        — Optional --watch mode for template live-reload
 */
import {
  StringHelper,
  FileHelper,
  CommandHelper,
  ParamHelper,
  Pipeline,
  Scaffold,
  Watcher,
} from '../../dist/index.js';

const DIVIDER = '-'.repeat(55);

async function main() {
  const startTime = performance.now();
  console.log('\n  SCG Landing Page Demo - Vite + React + TypeScript\n');
  console.log(DIVIDER);

  // -------------------------------------------------------
  // 1. PARAM HELPER — Parse CLI arguments
  // -------------------------------------------------------
  const params = ParamHelper.getParams();
  const nameRaw = params.name || 'MyApp';
  const titleRaw = params.title || `${nameRaw} — Landing Page`;
  const descriptionRaw = params.description || 'A modern landing page built with React and TypeScript';
  const watchMode = process.argv.includes('--watch');

  console.log('\n[1/7] ParamHelper - Parsed CLI arguments');
  console.log(`      name        : ${nameRaw}`);
  console.log(`      title       : ${titleRaw}`);
  console.log(`      description : ${descriptionRaw}`);
  console.log(`      watch       : ${watchMode}`);

  // -------------------------------------------------------
  // 2. STRING HELPER — Transform project names
  // -------------------------------------------------------
  const name = StringHelper.capitalize(nameRaw);
  const nameLower = nameRaw.toLowerCase();
  const nameKebab = nameLower.replace(/\s+/g, '-');
  const title = titleRaw;
  const description = descriptionRaw;
  const timestamp = new Date().toISOString().split('T')[0];

  const variables = {
    name,
    nameLower,
    nameKebab,
    title,
    description,
    timestamp,
  };

  console.log('\n[2/7] StringHelper - Name transformations');
  console.log(`      Capitalized : ${name}`);
  console.log(`      lowercase   : ${nameLower}`);
  console.log(`      kebab-case  : ${nameKebab}`);

  // -------------------------------------------------------
  // 3. SCAFFOLD — Generate React + CSS + HTML from EJS
  // -------------------------------------------------------
  const outputDir = `./generated/${nameKebab}-landing`;

  console.log('\n[3/7] Scaffold - Generating Vite + React project with EJS...');

  const scaffoldResult = await Scaffold.from({
    engine: 'EJS',
    templateDir: './example/landing-page-demo/templates',
    outputDir,
    variables,
    structure: [
      { template: 'index-html.ejs', output: 'index.html' },
      { template: 'main.ejs', output: 'src/main.tsx' },
      { template: 'app.ejs', output: 'src/App.tsx' },
      { template: 'app-css.ejs', output: 'src/App.css' },
      { template: 'index-css.ejs', output: 'src/index.css' },
      { template: 'vite-env.ejs', output: 'src/vite-env.d.ts' },
      { template: 'vite-svg.ejs', output: 'public/vite.svg' },
    ],
  });

  for (const file of scaffoldResult.files) {
    console.log(`      + ${file}`);
  }

  // -------------------------------------------------------
  // 4. PIPELINE — README with Handlebars + footer transform
  // -------------------------------------------------------
  console.log('\n[4/7] Pipeline - Generating README...');

  await new Pipeline()
    .fromTemplate('example/landing-page-demo/templates/readme.handlebars', variables)
    .transform((content) => content + `\n---\n\n*Generated by SCG on ${timestamp}*\n`)
    .writeTo(`${outputDir}/README.md`);
  console.log(`      + ${outputDir}/README.md  (Handlebars + footer transform)`);

  // -------------------------------------------------------
  // 5. FILE HELPER — package.json, tsconfig, vite.config,
  //    vercel.json, .gitignore, deploy script
  // -------------------------------------------------------
  console.log('\n[5/7] FileHelper - Creating project configs...');

  // package.json
  const packageJson = {
    name: nameKebab,
    private: true,
    version: '0.0.0',
    type: 'module',
    scripts: {
      dev: 'vite',
      build: 'tsc -b && vite build',
      preview: 'vite preview',
      deploy: 'vercel',
      'deploy:prod': 'vercel --prod',
    },
    dependencies: {
      react: '^19.0.0',
      'react-dom': '^19.0.0',
    },
    devDependencies: {
      '@types/react': '^19.0.0',
      '@types/react-dom': '^19.0.0',
      '@vitejs/plugin-react': '^4.3.0',
      typescript: '~5.7.0',
      vite: '^6.1.0',
      vercel: '^39.0.0',
    },
  };

  await FileHelper.writeFileAsync(
    `${outputDir}/package.json`,
    JSON.stringify(packageJson, null, 2) + '\n'
  );
  console.log(`      + ${outputDir}/package.json`);

  // tsconfig.json
  const tsconfigJson = {
    files: [],
    references: [
      { path: './tsconfig.app.json' },
      { path: './tsconfig.node.json' },
    ],
  };

  await FileHelper.writeFileAsync(
    `${outputDir}/tsconfig.json`,
    JSON.stringify(tsconfigJson, null, 2) + '\n'
  );
  console.log(`      + ${outputDir}/tsconfig.json`);

  // tsconfig.app.json
  const tsconfigApp = {
    compilerOptions: {
      tsBuildInfoFile: './node_modules/.tmp/tsconfig.app.tsbuildinfo',
      target: 'ES2020',
      useDefineForClassFields: true,
      lib: ['ES2020', 'DOM', 'DOM.Iterable'],
      module: 'ESNext',
      skipLibCheck: true,
      moduleResolution: 'bundler',
      allowImportingTsExtensions: true,
      isolatedModules: true,
      moduleDetection: 'force',
      noEmit: true,
      jsx: 'react-jsx',
      strict: true,
      noUnusedLocals: true,
      noUnusedParameters: true,
      noFallthroughCasesInSwitch: true,
      noUncheckedSideEffectImports: true,
    },
    include: ['src'],
  };

  await FileHelper.writeFileAsync(
    `${outputDir}/tsconfig.app.json`,
    JSON.stringify(tsconfigApp, null, 2) + '\n'
  );
  console.log(`      + ${outputDir}/tsconfig.app.json`);

  // tsconfig.node.json
  const tsconfigNode = {
    compilerOptions: {
      tsBuildInfoFile: './node_modules/.tmp/tsconfig.node.tsbuildinfo',
      target: 'ES2022',
      lib: ['ES2023'],
      module: 'ESNext',
      skipLibCheck: true,
      moduleResolution: 'bundler',
      allowImportingTsExtensions: true,
      isolatedModules: true,
      moduleDetection: 'force',
      noEmit: true,
      strict: true,
      noUnusedLocals: true,
      noUnusedParameters: true,
      noFallthroughCasesInSwitch: true,
      noUncheckedSideEffectImports: true,
    },
    include: ['vite.config.ts'],
  };

  await FileHelper.writeFileAsync(
    `${outputDir}/tsconfig.node.json`,
    JSON.stringify(tsconfigNode, null, 2) + '\n'
  );
  console.log(`      + ${outputDir}/tsconfig.node.json`);

  // vite.config.ts
  const viteConfig = [
    `import { defineConfig } from 'vite'`,
    `import react from '@vitejs/plugin-react'`,
    ``,
    `// https://vite.dev/config/`,
    `export default defineConfig({`,
    `  plugins: [react()],`,
    `})`,
    ``,
  ].join('\n');

  await FileHelper.writeFileAsync(`${outputDir}/vite.config.ts`, viteConfig);
  console.log(`      + ${outputDir}/vite.config.ts`);

  // vercel.json
  const vercelJson = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    framework: 'vite',
    buildCommand: 'pnpm build',
    outputDirectory: 'dist',
  };

  await FileHelper.writeFileAsync(
    `${outputDir}/vercel.json`,
    JSON.stringify(vercelJson, null, 2) + '\n'
  );
  console.log(`      + ${outputDir}/vercel.json`);

  // .gitignore
  const gitignore = [
    '# Dependencies',
    'node_modules',
    '',
    '# Build',
    'dist',
    '',
    '# IDE',
    '.vscode/*',
    '!.vscode/extensions.json',
    '.idea',
    '*.suo',
    '*.ntvs*',
    '*.njsproj',
    '*.sln',
    '*.sw?',
    '',
    '# Env',
    '.env.local',
    '.env.*.local',
    '',
    '# Vercel',
    '.vercel',
    '',
  ].join('\n');

  await FileHelper.writeFileAsync(`${outputDir}/.gitignore`, gitignore);
  console.log(`      + ${outputDir}/.gitignore`);

  // deploy.sh
  const deployScript = [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    '',
    'DIR="$(cd "$(dirname "$0")" && pwd)"',
    'cd "$DIR"',
    '',
    'echo ""',
    `echo "  ${name} Landing Page — Deploy to Vercel"`,
    'echo "  ─────────────────────────────────────────────"',
    'echo ""',
    '',
    'if ! command -v vercel &> /dev/null; then',
    '  echo "  [!] Vercel CLI not found. Installing..."',
    '  pnpm add -g vercel',
    'fi',
    '',
    'echo "  [1/3] Installing dependencies..."',
    'pnpm install --silent',
    '',
    'echo "  [2/3] Building project..."',
    'pnpm build',
    '',
    'echo "  [3/3] Deploying to Vercel..."',
    'PROD="${1:-}"',
    'if [ "$PROD" = "--prod" ]; then',
    '  vercel --prod',
    'else',
    '  vercel',
    'fi',
    '',
    'echo ""',
    'echo "  Done!"',
    'echo ""',
    '',
  ].join('\n');

  await FileHelper.writeFileAsync(`${outputDir}/deploy.sh`, deployScript);
  await CommandHelper.run('.', `chmod +x ${outputDir}/deploy.sh`);
  console.log(`      + ${outputDir}/deploy.sh`);

  // -------------------------------------------------------
  // 6. COMMAND HELPER — Show generated file listing
  // -------------------------------------------------------
  console.log('\n[6/7] CommandHelper - Generated files:');

  const listing = await CommandHelper.run('.', `ls -1R ${outputDir}`);
  const fileList = listing.trim().split('\n').filter(Boolean);
  for (const f of fileList) {
    console.log(`      ${f.trim()}`);
  }

  // -------------------------------------------------------
  // Summary
  // -------------------------------------------------------
  const totalFiles = fileList.length;
  const elapsed = ((performance.now() - startTime) / 1000).toFixed(2);
  console.log('\n' + DIVIDER);
  console.log(`  Done! Generated ${totalFiles} files in ${outputDir}/ (${elapsed}s)\n`);
  console.log('  Engines used:');
  console.log('    EJS        -> 7 files (index.html, main.tsx, App.tsx, App.css, index.css, vite-env.d.ts, vite.svg)');
  console.log('    Handlebars -> 1 file  (README.md)');
  console.log('    FileHelper -> 8 files (package.json, tsconfig x3, vite.config.ts, vercel.json, .gitignore, deploy.sh)\n');
  console.log('  Quick start:\n');
  console.log(`    cd ${outputDir}`);
  console.log('    pnpm install');
  console.log('    pnpm dev\n');
  console.log('  Deploy to Vercel:\n');
  console.log(`    cd ${outputDir}`);
  console.log('    pnpm deploy          # preview deployment');
  console.log('    pnpm deploy:prod     # production deployment');
  console.log(`    # or: ${outputDir}/deploy.sh [--prod]`);
  console.log(DIVIDER);

  // -------------------------------------------------------
  // 7. WATCHER — Optional --watch mode
  // -------------------------------------------------------
  if (watchMode) {
    console.log('\n[7/7] Watcher - Watching templates for changes...');
    console.log('      Edit files in example/landing-page-demo/templates/ to trigger rebuild');
    console.log('      Press Ctrl+C to stop\n');

    const watcher = new Watcher({
      templateDir: './example/landing-page-demo/templates',
      outputDir,
      engine: 'EJS',
      variables,
      onRebuild: (file) => console.log(`      Rebuilt: ${file}`),
      onError: (err, file) => console.error(`      Error in ${file}: ${err.message}`),
    });
    watcher.start();
  } else {
    console.log('\n  Tip: Add --watch to re-generate on template changes\n');
  }
}

main().catch(console.error);
